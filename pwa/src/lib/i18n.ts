export const dictionaries: Record<Lang, Dict> = { de: de as Dict, en }

export type Translate = (key: Key, vars?: Record<string, string | number>) => string

export function makeT(lang: Lang): Translate {
  const dict = dictionaries[lang]
  return (key, vars) => {
    const text = dict[key] ?? key
    return vars ? text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : text
  }
}

/** Device language: German if the first preferred language is German, otherwise English. */
export function detectLang(navigatorLanguages: readonly string[]): Lang {
  return navigatorLanguages[0]?.toLowerCase().startsWith("de") ? "de" : "en"
}
